/**
 * ExportButton.jsx — Reusable CSV + PDF export component.
 * Usage: <ExportButton data={rows} filename="my-export" dashboardName="Policymaker" />
 */

import { useState, useRef, useEffect } from 'react'
import { Download, ChevronDown, FileText, Table } from 'lucide-react'
import { useAuth } from '../context/AuthContext'

function formatDate() {
  return new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
}

async function exportCSV(data, filename) {
  if (!data?.length) return
  const { unparse } = await import('papaparse')
  const csv = unparse(data)
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' })
  const url  = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href     = url
  link.download = `${filename}-${new Date().toISOString().slice(0,10)}.csv`
  link.click()
  URL.revokeObjectURL(url)
}

async function exportPDF(data, filename, dashboardName, userRole) {
  if (!data?.length) return
  const { default: jsPDF }  = await import('jspdf')
  const { default: autoTable } = await import('jspdf-autotable')

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })

  // Header
  doc.setFillColor(10, 35, 66)
  doc.rect(0, 0, 297, 28, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(18)
  doc.setFont('helvetica', 'bold')
  doc.text('Louisiana EduPulse', 14, 12)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text(`${dashboardName || ''} Dashboard Export`, 14, 20)
  doc.setFontSize(9)
  doc.text(`Generated: ${formatDate()} · Role: ${userRole || 'N/A'}`, 200, 20)

  // Table
  const headers = Object.keys(data[0])
  const rows    = data.map(row => headers.map(h => {
    const v = row[h]
    return v === null || v === undefined ? '' : String(v)
  }))

  autoTable(doc, {
    startY:      32,
    head:        [headers],
    body:        rows,
    headStyles:  { fillColor: [46, 196, 182], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
    bodyStyles:  { fontSize: 7, cellPadding: 2 },
    alternateRowStyles: { fillColor: [245, 248, 250] },
    margin:      { left: 14, right: 14 },
  })

  // Footer
  const pageCount = doc.internal.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    const y = doc.internal.pageSize.height - 8
    doc.setFontSize(7)
    doc.setTextColor(100, 116, 139)
    doc.text('Data sources: LDOE, US Census ACS, BLS Louisiana | Generated by Louisiana EduPulse', 14, y)
    doc.text(`Page ${i} of ${pageCount}`, 270, y)
  }

  doc.save(`${filename}-${new Date().toISOString().slice(0,10)}.pdf`)
}

export default function ExportButton({ data = [], filename = 'edupulse-export', dashboardName = '', isDark = false }) {
  const { user }    = useAuth()
  const [open, setOpen]   = useState(false)
  const [busy, setBusy]   = useState(false)
  const ref = useRef(null)

  // Close dropdown on outside click
  useEffect(() => {
    function onOut(e) { if (ref.current && !ref.current.contains(e.target)) setOpen(false) }
    document.addEventListener('mousedown', onOut)
    return () => document.removeEventListener('mousedown', onOut)
  }, [])

  async function handleCSV() {
    setBusy(true); setOpen(false)
    await exportCSV(data, filename)
    setBusy(false)
  }

  async function handlePDF() {
    setBusy(true); setOpen(false)
    await exportPDF(data, filename, dashboardName, user?.role)
    setBusy(false)
  }

  return (
    <div ref={ref} className="relative">
      <button
        onClick={() => setOpen(o => !o)}
        disabled={busy || !data?.length}
        className={`inline-flex items-center gap-1.5 px-3 py-2 rounded-lg text-xs font-medium transition-all cursor-pointer
          ${isDark
            ? 'bg-white/8 border border-white/10 text-slate-brand hover:text-white hover:border-white/20'
            : 'bg-white border border-navy/10 text-navy/60 hover:text-navy hover:border-navy/20 shadow-sm'
          } ${(busy || !data?.length) ? 'opacity-50 cursor-not-allowed' : ''}`}
      >
        {busy ? (
          <div className="w-3 h-3 border border-current/30 border-t-current rounded-full animate-spin" />
        ) : (
          <Download size={13} />
        )}
        Export
        <ChevronDown size={11} className={`transition-transform ${open ? 'rotate-180' : ''}`} />
      </button>

      {open && (
        <div className={`absolute right-0 top-full mt-1 w-44 rounded-xl border shadow-lg z-50 overflow-hidden
          ${isDark ? 'bg-navy-2 border-white/10' : 'bg-white border-navy/10'}`}>
          <button onClick={handleCSV}
            className={`w-full flex items-center gap-2.5 px-4 py-3 text-xs text-left transition-colors cursor-pointer
              ${isDark ? 'text-slate-brand hover:bg-white/5 hover:text-white' : 'text-navy/70 hover:bg-slate-50 hover:text-navy'}`}>
            <Table size={13} className="text-teal-2" />
            Download CSV
          </button>
          <button onClick={handlePDF}
            className={`w-full flex items-center gap-2.5 px-4 py-3 text-xs text-left transition-colors cursor-pointer border-t
              ${isDark ? 'text-slate-brand hover:bg-white/5 hover:text-white border-white/8' : 'text-navy/70 hover:bg-slate-50 hover:text-navy border-navy/8'}`}>
            <FileText size={13} className="text-gold" />
            Download PDF
          </button>
        </div>
      )}
    </div>
  )
}
