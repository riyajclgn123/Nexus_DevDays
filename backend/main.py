"""
main.py

FastAPI application entry point.

This is the file you run to start the backend server:
    uvicorn main:app --reload

What this file does:
  - Creates the FastAPI app instance
  - Sets up CORS (allows React frontend to make requests)
  - Registers all routers (parishes, metrics, opportunities, etc.)
  - Creates database tables on startup
  - Provides health check endpoint

API documentation (auto-generated by FastAPI):
  http://localhost:8000/docs       ← Swagger UI
  http://localhost:8000/redoc      ← ReDoc UI
"""

import os
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from dotenv import load_dotenv

# Import database and models
from database import engine, Base
import models  # importing ensures all models are registered with SQLAlchemy

# Import all routers
from routers.parishes import router as parishes_router
from routers.metrics import router as metrics_router
from routers.opportunities import (
    opps_router, sites_router, alerts_router, workforce_router
)
from routers.chat import router as chat_router

# Load .env variables
load_dotenv()

# ─── Create FastAPI app ───────────────────────────────────────────
app = FastAPI(
    title="Louisiana EduPulse API",
    description="""
    Backend API for the Louisiana EduPulse platform.
    
    Provides real Louisiana education data from:
    - Louisiana Department of Education (LDOE) 2024
    - US Census Bureau ACS 2024
    - BLS Louisiana Workforce Data 2025
    - Leaders for a Better Louisiana Research
    
    Used by the EduPulse React frontend to power three
    role-based dashboards: Policymaker, Funder, and Operator.
    """,
    version="1.0.0",
    docs_url="/docs",
    redoc_url="/redoc",
)

# ─── CORS Middleware ──────────────────────────────────────────────
# This is REQUIRED — without it, your React app (localhost:5173)
# cannot make requests to your FastAPI server (localhost:8000)
# because browsers block cross-origin requests by default.

frontend_url = os.getenv("FRONTEND_URL", "http://localhost:5173")

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        frontend_url,
        "http://localhost:5173",
        "http://localhost:3000",
        "http://127.0.0.1:5173",
    ],
    allow_credentials=True,
    allow_methods=["*"],    # GET, POST, PUT, DELETE, etc.
    allow_headers=["*"],    # Authorization, Content-Type, etc.
)

# ─── Create database tables on startup ───────────────────────────
# This runs Base.metadata.create_all() which looks at all your
# models and creates the tables if they don't exist yet.
@app.on_event("startup")
async def startup():
    Base.metadata.create_all(bind=engine)
    print("✅ Database tables ready")

# ─── Register all routers ─────────────────────────────────────────
# Each router adds a group of endpoints to the app.
# prefix="/api/v1" means all URLs start with /api/v1/...

app.include_router(parishes_router,  prefix="/api/v1")
app.include_router(metrics_router,   prefix="/api/v1")
app.include_router(opps_router,      prefix="/api/v1")
app.include_router(sites_router,     prefix="/api/v1")
app.include_router(alerts_router,    prefix="/api/v1")
app.include_router(workforce_router, prefix="/api/v1")
app.include_router(chat_router,      prefix="/api/v1")

# ─── Root and health check endpoints ─────────────────────────────
@app.get("/")
def root():
    return {
        "message":  "Louisiana EduPulse API",
        "version":  "1.0.0",
        "status":   "running",
        "docs":     "http://localhost:8000/docs",
        "endpoints": {
            "parishes":     "/api/v1/parishes/",
            "metrics":      "/api/v1/metrics/summary",
            "sps_history":  "/api/v1/metrics/sps-history",
            "proficiency":  "/api/v1/metrics/proficiency",
            "opportunities":"/api/v1/opportunities/",
            "sites":        "/api/v1/sites/",
            "alerts":       "/api/v1/alerts/",
            "workforce":    "/api/v1/workforce/",
        }
    }

@app.get("/health")
def health_check():
    """Simple health check — returns 200 if API is running."""
    return {"status": "healthy", "api": "EduPulse v1.0"}
